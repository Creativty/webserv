#include "base.hpp"

void	MEM_copy(byte* src, i32 src_len, byte* dst, i32 dst_len) {
	if (src == 0 || dst == 0) {
		return ;
	}

	for (i32 i = 0; i < src_len && i < dst_len; ++i) {
		dst[i] = src[i];
	}
}
